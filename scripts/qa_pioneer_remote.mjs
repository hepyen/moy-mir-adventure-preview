import {chromium} from 'playwright-core';
import {readFileSync} from 'node:fs';
const bank=readFileSync('src/pioneer/bank.txt','utf8').trim().split(/\r?\n/).map(x=>x.split('|'));
const b=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--no-sandbox']});
const p=await b.newPage({viewport:{width:1920,height:1080}});
await p.goto('http://127.0.0.1:4191/',{waitUntil:'networkidle'});
const focus=()=>p.evaluate(()=>({text:document.activeElement?.textContent?.trim()?.slice(0,90),className:document.activeElement?.className}));
const initial=await focus();
if(!String(initial.className).includes('pn-level'))throw Error('TV launch focus missing');
console.log('LOBBY_FOCUS',initial.text);
await p.keyboard.press('Enter');
if(await p.locator('.pn-option').count()!==4)throw Error('OK failed to start level');
const title=(await p.locator('.pn-question-wrap h1').textContent())?.trim();
const correct=bank.find(x=>x[0]===title)?.[1];
const options=await p.locator('.pn-option > span:nth-child(2)').allTextContents();
const index=options.findIndex(x=>x===correct);
if(index<0)throw Error('Answer not found');
await p.keyboard.press('ArrowRight');
console.log('DPAD RIGHT',await focus());
if(index===0||index===2)await p.keyboard.press('ArrowLeft');
if(index===2||index===3)await p.keyboard.press('ArrowDown');
const focused=await focus();
if(!focused.text?.includes(correct))throw Error('Dpad did not reach correct answer '+correct+' '+JSON.stringify(focused));
console.log('DPAD SELECT',focused.text);
await p.keyboard.press('Enter');
await p.locator('.pn-feedback').waitFor();
await p.waitForTimeout(150);
const replyFocus=await focus();
if(!replyFocus.text?.includes('Следующий вопрос'))throw Error('Continue button not focused');
console.log('CONTINUE FOCUS',replyFocus.text);
await p.keyboard.press('Enter');
await p.locator('.pn-question-no').getByText('ВОПРОС 2 / 10').waitFor();
console.log('NEXT WITH OK',await p.locator('.pn-question-no').textContent());
await b.close();
