import {chromium} from 'playwright-core';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:720}});
const errors=[];const failed=[];page.on('pageerror',e=>errors.push(String(e)));page.on('response',r=>{if(r.status()===404)failed.push(r.url())});
await page.clock.install({time:new Date('2026-11-15T18:00:00Z')});
await page.goto('http://127.0.0.1:4191/',{waitUntil:'networkidle'});
await page.locator('.pn-level.open').first().click();
let text=(await page.locator('.pn-timer-value').textContent())?.trim();
if(text!=='30')throw Error('Expected 30, got '+text);
await page.clock.fastForward(26000);await page.waitForTimeout(100);
text=(await page.locator('.pn-timer-value').textContent())?.trim();
if(text!=='4')throw Error('Expected 4 sec after 26, got '+text);
if(!await page.locator('.pn-timer.danger').isVisible())throw Error('Timer did not turn danger');
await page.clock.fastForward(5000);await page.waitForTimeout(250);
const feedback=await page.locator('.pn-feedback').allTextContents();
if(!feedback.join('').includes('Время вышло'))throw Error('Timeout failed '+feedback);
await page.locator('.pn-feedback button').click();
await page.locator('.pn-result h1').waitFor();
const won=(await page.locator('.pn-result-score strong').textContent())?.trim();
if(won!=='+0')throw Error('Timeout before milestone awarded '+won);
console.log('PASS TIMER 30s, red warning at 4, 0 ends game, 0 prize');
console.log('404s',failed,'JS_ERRORS',errors);
await browser.close();
if(failed.length||errors.length)process.exitCode=1;
