import {chromium} from 'playwright-core';
import {readFileSync} from 'node:fs';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1920,height:1080},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(String(error)));
await page.goto('http://127.0.0.1:4191/',{waitUntil:'networkidle'});
await page.screenshot({path:'docs/qa-pioneer-tv-lobby.png',fullPage:true});
console.log('LOBBY',await page.locator('.pn-level').count(),await page.locator('.pn-hero h1').textContent());
await page.locator('.pn-level.open').first().click();
await page.locator('.pn-option').first().waitFor();
console.log('GAME',await page.locator('.pn-option').count(),await page.locator('.pn-question-wrap h1').textContent());
await page.screenshot({path:'docs/qa-pioneer-tv-question.png',fullPage:true});
await page.getByRole('button',{name:'♟ Зал'}).click();
const voteSums=(await page.locator('.pn-vote-bars small').allTextContents()).map(x=>parseInt(x));
if(voteSums.reduce((a,b)=>a+b,0)!==100)throw Error('Audience votes must sum to 100');
await page.getByRole('button',{name:'50:50'}).click();
const visible=await page.locator('.pn-option:not([disabled])').count();
if(visible!==2)throw Error('50:50 removed incorrect count: '+visible);
const raw=readFileSync('src/pioneer/bank.txt','utf-8').trim().split(/\r?\n/).map(x=>x.split('|'));
let seen=[];
for(let i=0;i<10;i++){
 const title=(await page.locator('.pn-question-wrap h1').textContent())?.trim();
 const match=raw.find(row=>row[0]===title);
 if(!match)throw Error('Unknown question '+title);
 seen.push(title);
 const correct=match[1];
 await page.locator('.pn-option').filter({hasText:correct}).click();
 console.log('QUESTION',i+1,'TITLE',title,'CORRECT',correct,'FEEDBACK',await page.locator('.pn-feedback').allTextContents());
 await page.locator('.pn-feedback button').click();
}
await page.getByRole('button',{name:/Вернуться к достижениям/}).click();
const total=(await page.locator('.pn-hero-stat b').first().textContent())?.trim();
if(total!=='10')throw Error('Unexpected points '+total);
if(await page.locator('.pn-level.open').count()!==2)throw Error('Level two did not unlock');
console.log('PASS first round',seen.length,'unique',new Set(seen).size,'balance',total);
console.log('BROWSER_ERRORS',errors);
await browser.close();
if(errors.length)process.exitCode=1;
