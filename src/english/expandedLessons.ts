 const extra:EnglishQuestion[]=rows.map(([prompt,right,wrongA,wrongB,explain])=>{
  const arr=[right,wrongA,wrongB],rotation=seedFor(id+':'+prompt)%3
  const options=[...arr.slice(rotation),...arr.slice(0,rotation)] as [string,string,string]
  if(new Set(options).size!==3)throw Error('Ambiguous answers: '+prompt)
  return {prompt,options,correct:options.indexOf(right),explain,topic:id}
 })
