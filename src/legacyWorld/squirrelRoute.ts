 const route=points>=950?SQUIRREL_ROUTE:points>=520?STAIR_ROUTE:LAWN_ROUTE
 const phase=Math.max(0,progress%1)*(route.length-1)
 const index=Math.min(route.length-2,Math.floor(phase))
 const t=phase-index
 const a=route[index],b=route[index+1]
